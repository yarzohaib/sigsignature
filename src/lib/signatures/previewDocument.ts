export const SIGNATURE_FONTS_HREF =
  "https://fonts.googleapis.com/css2?family=Commissioner:wght@400;500;600;700&family=DM+Sans:wght@400;500;700&family=Inter:wght@400;500;600;700&family=Montserrat:wght@400;500;600;700&family=Roboto:wght@400;500;700&display=swap";

const BASE_RESET =
  "* { box-sizing: border-box; } img { border: 0; outline: none; text-decoration: none; }";

export function buildPreviewDocument(
  signatureHtml: string,
  options?: { padding?: number }
): string {
  const padding = options?.padding ?? 16;
  return `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="${SIGNATURE_FONTS_HREF}" rel="stylesheet">
<style>
html, body { margin: 0; padding: ${padding}px; background-color: #ffffff; -webkit-font-smoothing: antialiased; }
${BASE_RESET}
</style>
</head>
<body>${signatureHtml}</body>
</html>`;
}

export function buildDownloadDocument(signatureHtml: string, title: string): string {
  const safeTitle = title.replace(/[<>&"]/g, "");
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${safeTitle} email signature</title>
<link href="${SIGNATURE_FONTS_HREF}" rel="stylesheet">
<style>
body { margin: 0; padding: 24px; background-color: #ffffff; }
${BASE_RESET}
</style>
</head>
<body>
<!-- Email signature generated by Sig Signature (www.sigsignature.com) -->
${signatureHtml}
</body>
</html>
`;
}